package org.shizavisuals.hud.island;

public class IslandSize {
    public float width;
    public float height;

    public void update(float width, float height) {
        this.width = width;
        this.height = height;
    }

    public IslandSize(float width, float height) {
        this.width = width;
        this.height = height;
    }
}
